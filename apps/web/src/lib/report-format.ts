import ExcelJS from "exceljs";
import { PDFDocument, StandardFonts, rgb, type PDFFont } from "pdf-lib";
import type { Report } from "@/lib/report";

/** A cell that starts with = + - @ can run as a formula in a spreadsheet. Prefix it so it cannot. */
export function csvSafe(v: string | number | null): string {
  if (v === null) return "";
  const s = String(v);
  const guarded = typeof v === "string" && /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return /[",\r\n]/.test(guarded)
    ? `"${guarded.replace(/"/g, '""')}"`
    : guarded;
}

function metaRows(r: Report): [string, string][] {
  return [
    ["Report", r.title],
    ["Scope", r.scope],
    ["Generated", r.generatedAt],
    ["Generated by", r.generatedBy],
    [
      "Data window",
      r.window ? `${r.window.from} to ${r.window.to}` : "all current records",
    ],
    ["Maturity", r.maturity],
    ...r.sources.map((s, i): [string, string] => [`Source ${i + 1}`, s]),
    ...r.assumptions.map((s, i): [string, string] => [
      `Assumption ${i + 1}`,
      s,
    ]),
  ];
}

export function toCsv(r: Report): string {
  const lines: string[] = [];
  for (const [k, v] of metaRows(r))
    lines.push([csvSafe(k), csvSafe(v)].join(","));
  for (const t of r.tables) {
    lines.push("");
    lines.push(csvSafe(t.title));
    lines.push(t.columns.map(csvSafe).join(","));
    for (const row of t.rows) lines.push(row.map(csvSafe).join(","));
    if (t.note) lines.push(csvSafe(`Note: ${t.note}`));
  }
  return lines.join("\r\n") + "\r\n";
}

function sheetName(title: string, used: Set<string>): string {
  const base =
    title
      .replace(/[\\/?*[\]:]/g, " ")
      .trim()
      .slice(0, 28) || "Sheet";
  let name = base;
  for (let n = 2; used.has(name.toLowerCase()); n++)
    name = `${base.slice(0, 26)} ${n}`;
  used.add(name.toLowerCase());
  return name;
}

export async function toXlsx(r: Report): Promise<Uint8Array> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "HydroSight";
  wb.created = new Date(r.generatedAt);
  const used = new Set<string>();
  const about = wb.addWorksheet(sheetName("About this report", used));
  about.columns = [{ width: 18 }, { width: 110 }];
  for (const [k, v] of metaRows(r))
    about.addRow([k, v]).getCell(2).alignment = {
      wrapText: true,
      vertical: "top",
    };
  about.getColumn(1).font = { bold: true };
  for (const t of r.tables) {
    const ws = wb.addWorksheet(sheetName(t.title, used));
    ws.addRow([t.title]).font = { bold: true, size: 12 };
    const head = ws.addRow(t.columns);
    head.font = { bold: true };
    for (const row of t.rows) ws.addRow(row.map((c) => (c === null ? "" : c))); // strings stay text, never formulas
    if (t.note) {
      ws.addRow([]);
      ws.addRow([`Note: ${t.note}`]).font = { italic: true };
    }
    t.columns.forEach((_, i) => (ws.getColumn(i + 1).width = 24));
  }
  const buf = await wb.xlsx.writeBuffer();
  return new Uint8Array(buf as ArrayBuffer);
}

// ---------- PDF ----------
const PAGE: [number, number] = [842, 595]; // A4 landscape
const M = 36;

/** Helvetica in pdf-lib is WinAnsi only; anything it cannot encode becomes "?" instead of failing. */
export function pdfText(s: string, font: PDFFont): string {
  let out = "";
  for (const ch of s
    .replace(/—/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')) {
    try {
      font.encodeText(ch);
      out += ch;
    } catch {
      out += "?";
    }
  }
  return out;
}

function wrap(
  text: string,
  font: PDFFont,
  size: number,
  width: number,
): string[] {
  const lines: string[] = [];
  for (const para of text.split(/\r?\n/)) {
    let cur = "";
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const next = cur ? `${cur} ${word}` : word;
      if (font.widthOfTextAtSize(next, size) <= width) cur = next;
      else {
        if (cur) lines.push(cur);
        let w = word;
        while (font.widthOfTextAtSize(w, size) > width && w.length > 1) {
          let k = w.length - 1;
          while (k > 1 && font.widthOfTextAtSize(w.slice(0, k), size) > width)
            k--;
          lines.push(w.slice(0, k));
          w = w.slice(k);
        }
        cur = w;
      }
    }
    lines.push(cur);
  }
  return lines;
}

export async function toPdf(r: Report): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(r.title);
  doc.setCreator("HydroSight");
  doc.setCreationDate(new Date(r.generatedAt));
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  let page = doc.addPage(PAGE);
  let y = PAGE[1] - M;
  const width = PAGE[0] - 2 * M;
  const ensure = (h: number) => {
    if (y - h < M + 14) {
      page = doc.addPage(PAGE);
      y = PAGE[1] - M;
    }
  };
  const para = (
    text: string,
    size: number,
    f: PDFFont = font,
    color = rgb(0.1, 0.1, 0.1),
  ) => {
    for (const line of wrap(pdfText(text, f), f, size, width)) {
      ensure(size + 3);
      page.drawText(line, { x: M, y: y - size, size, font: f, color });
      y -= size + 3;
    }
  };
  para(r.title, 16, bold);
  y -= 4;
  for (const [k, v] of metaRows(r)) para(`${k}: ${v}`, 8.5);
  for (const t of r.tables) {
    y -= 10;
    ensure(40);
    para(t.title, 11, bold);
    const colW = width / t.columns.length;
    const drawRow = (cells: string[], f: PDFFont) => {
      const wrapped = cells.map((c) => wrap(pdfText(c, f), f, 7.5, colW - 6));
      const lines = Math.max(...wrapped.map((w) => w.length), 1);
      ensure(lines * 9 + 4);
      wrapped.forEach((w, ci) =>
        w.forEach((ln, li) =>
          page.drawText(ln, {
            x: M + ci * colW,
            y: y - 8 - li * 9,
            size: 7.5,
            font: f,
            color: rgb(0.1, 0.1, 0.1),
          }),
        ),
      );
      y -= lines * 9 + 3;
      page.drawLine({
        start: { x: M, y: y + 1 },
        end: { x: M + width, y: y + 1 },
        thickness: 0.3,
        color: rgb(0.75, 0.8, 0.85),
      });
    };
    drawRow(t.columns, bold);
    for (const row of t.rows)
      drawRow(
        row.map((c) => (c === null ? "" : String(c))),
        font,
      );
    if (t.note) para(`Note: ${t.note}`, 8, font, rgb(0.3, 0.3, 0.3));
  }
  const pages = doc.getPages();
  pages.forEach((p, i) =>
    p.drawText(
      `HydroSight  |  ${pdfText(r.title, font)}  |  page ${i + 1} of ${pages.length}`,
      { x: M, y: 18, size: 7, font, color: rgb(0.4, 0.4, 0.4) },
    ),
  );
  return doc.save();
}

export async function sha256Hex(bytes: Uint8Array | string): Promise<string> {
  const data =
    typeof bytes === "string" ? new TextEncoder().encode(bytes) : bytes;
  const digest = await crypto.subtle.digest("SHA-256", data as BufferSource);
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

export const FORMATS = {
  csv: { mime: "text/csv; charset=utf-8", ext: "csv" },
  xlsx: {
    mime: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ext: "xlsx",
  },
  pdf: { mime: "application/pdf", ext: "pdf" },
} as const;
export type Format = keyof typeof FORMATS;

export async function render(r: Report, f: Format): Promise<Uint8Array> {
  if (f === "csv") return new TextEncoder().encode(toCsv(r));
  return f === "xlsx" ? toXlsx(r) : toPdf(r);
}
